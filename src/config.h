#pragma once
#include <string>

// Формат: строки "ключ=значение", '#' — комментарий. Читается root-companion'ом из
//   /data/adb/myfg/config            (глобально)
//   /data/adb/myfg/config.d/<pkg>    (переопределения для пакета)
// и приходит в игру одним блобом. Изменения применяются при следующем запуске игры.
struct Config {
    int enable       = 1;
    int min_fps      = 0;     // ниже этого измеренного FPS источника интерполяцию не делаем (только проброс); 0 = выкл.
                              // Это нижняя планка поверх штатного порога WFG (выкл. <20, вкл. >24 fps):
                              // значения меньше 20 ничего не меняют, смысл имеют только 20 и выше
    int max_dt_ms    = 120;   // пауза между кадрами больше этого = сцена встала, без интерполяции (минимум 50:
                              // меньшее значение отключает генерацию в играх ниже ~1000/значение fps)
    int acq_fence    = 1;     // ждать acquire-fence игры перед копированием (см. capture.cpp)
    // Окно игры берётся из Surface::hook_queueBuffer (hook_surface: 0 — выкл, 1 — вкл). Остальные способы
    // (hook_egl, hook_anw): 0 — выключено, 1 — только если хук Surface не встал, 2 — всегда.
    int hook_surface = 1;     // хук android::Surface::hook_queueBuffer: окно + буфер + acquire-fence
    int hook_egl     = 1;     // окно через eglCreateWindowSurface
    int hook_anw     = 1;     // окно через ANativeWindow_fromSurface
    // Патч imageUsage свопчейна (inline-хук vkGetInstanceProcAddr/vkGetDeviceProcAddr).
    // По умолчанию ВЫКЛ: эти экспорты libvulkan — крошечные заглушки, патч затирает соседей.
    // Функции короче 16 байт хук всё равно не получат (см. inline_hook).
    int hook_vk      = 0;
    int hook_delay_ms = 0;    // пауза перед установкой хуков (для поиска причины зависаний при старте)
    int zorder       = 1;     // z-order дочернего слоя
    int display_fps  = 0;     // фиксированная подсказка частоты слоя для SurfaceFlinger (0 = не трогать)
    int auto_rate    = 0;     // 1 = если display_fps=0, выставлять слою частоту src_fps*(gen+1) автоматически
    int dataspace    = 1;     // 1 = передавать dataspace игры (QueueBufferInput+12) слою-оверлею
    int hide_ms      = 300;   // сколько мс без кадров держать оверлей; потом он прячется и виден слой игры (0 = не прятать)
    int release_lag  = 3;     // сколько output-кадров держим реальный кадр после показа
    int stats        = 1;     // писать статистику в logcat (раз в 5 с; при debug=1 — каждую секунду)
    int target_w     = 0;     // принудительный размер "игрового" буфера (0 = авто)
    int target_h     = 0;
    int max_gen      = 3;     // максимум сгенерированных кадров на кадр игры (WFG: до 7)
    int target_fps   = 0;     // целевой FPS вывода для плана WFG (0 = по частоте дисплея)
    int flow_side    = 180;   // меньшая сторона для оптического потока WFG

    // ---- запасные пути захвата ------------------------------------------------------------------
    // Запасные пути захвата (когда BufferQueue-хуки libgui недоступны или игра не отдаёт кадры через них).
    //   0 — выкл; 1 — запасной (включается, если BufferQueue-хуки не встали или кадров нет fallback_ms);
    //   2 — всегда установлен (для Vulkan это единственный способ перехватить vkCreateDevice вовремя).
    // Источником кадров всегда остаётся BufferQueue, как только он начинает отдавать кадры.
    int hook_swap    = 1;     // eglSwapBuffers / eglSwapBuffersWithDamageKHR (GLES-игры)
    int hook_present = 1;     // vkQueuePresentKHR (+ vkCreateDevice/vkCreateSwapchainKHR); см. README
    int fallback_ms  = 10000; // через сколько мс без кадров от BufferQueue включается режим «запасной»
    // Частота панели.
    int panel_hz       = 120; // подсказка SurfaceFlinger для слоя и окна игры (0 = не трогать)
    int panel_game_vote = 1;  // 1 = ту же подсказку ставить окну игры (ANativeWindow_setFrameRate...)
    int panel_anchor   = 0;   // 1 = отдельный слой-«якорь» обновляется с частотой панели (держит голос даже без оверлея)
    // Режим множителя: 0 = план WFG по частоте дисплея; N>=2 = ровно N-1 кадров на кадр игры (x2, x3, x4...),
    // но не больше, чем способен показать дисплей.
    int multiplier   = 0;
    // Детект повторных кадров (игра постит 60 к/с при 30 уникальных).
    int dup_detect   = 0;
    int dup_thresh   = 2;     // средняя разность по сетке отсчётов (0..255), не больше — кадр считается повтором
    // Освобождение буферов по ASurfaceTransaction_setOnComplete (иначе — эвристика release_lag).
    int use_oncomplete = 1;
    int queue_prio   = 1;     // 1 = просить у драйвера высокий приоритет очереди (VK_*_global_priority)
    int elect_blast  = 1;     // 1 = хук BLASTBufferQueue::update: размеры окон помогают выбрать игровую очередь
    // Источники, чьи кадры приходят через Binder (видео из MediaCodec, GPU-процесс браузера в SurfaceView): окно
    // игры у них неизвестно. 1 = хук BLASTBufferQueue::onFrameAvailable ставится лениво, когда такой источник
    // замечен, и по нему берётся поверхность SurfaceView (слой оверлея встаёт ровно на неё и остаётся под UI
    // приложения). 0 = выкл.: такие источники не выбираются (оверлей на чужое окно не вешаем никогда).
    int hook_bbq     = 1;
    // 1 = разрешить выбирать кадры окна самого приложения (HWUI, RenderThread: тулбары, меню, прозрачная «дыра»
    // под SurfaceView). По умолчанию 0: такой источник не нужен и закрывает видео чёрным прямоугольником.
    int ui_source    = 0;
    int layer_tf     = -1;    // -1 = transform из QueueBufferInput; 0..7 = принудительный transform слоя
    // перекодируется в BT.2020 + PQ, слой помечается dataspace 0x09c60000. Нужна панель с HDR.
    int hdr          = 0;     // 1 = включить
    int hdr_pw       = 200;   // paper white: до скольких нит поднимается белый SDR (100..1000)
    int hdr_peak     = 0;     // пик панели, нит: 0 = из Display.getHdrCapabilities() (при неудаче 1000), 400..1400 = вручную
    int hdr_knee     = 60;    // % яркости, с которого начинается растяжение светов (10..100)
    int hdr_boost    = 30;    // % запаса «пик/paper white», на который растягивается белый (0..100)
    int hdr_gamma    = 22;    // гамма*10 для линеаризации SDR: 18..26; 0 = кривая sRGB
    int hdr_ct       = 100;   // контраст, % (50..150)
    int hdr_sat      = 100;   // насыщенность, % (50..150)
    // Адаптивная нагрузка: время GPU нашего submit сравнивается с долей интервала между кадрами игры;
    // при перегрузе сначала падает разрешение потока (flow_side), затем число сгенерированных кадров.
    int adaptive     = 1;
    int gpu_budget   = 50;    // % интервала источника, который модуль может занимать на GPU
    int live         = 1;     // 1 = подхватывать изменения настроек без перезапуска игры
    // Счётчик FPS поверх игры (свой слой myfg_hud, см. hud.h)
    int hud          = 0;     // 1 = показывать
    int hud_mode     = 2;     // 0 = FPS; 1 = игра>вывод; 2 = FPS / GAME / GEN / GPU построчно
    int hud_pos      = 0;     // угол: 0 лев.верх, 1 прав.верх, 2 лев.низ, 3 прав.низ
    int hud_scale    = 3;     // размер текста, пикселей на пиксель шрифта (1..8)
    int hud_tf       = 0;     // transform слоя счётчика (как layer_tf, 0..7): поворот, если игра рисует с pre-rotation
    int debug        = 0;     // 1 = подробный лог (адреса, форматы, первые кадры) и статистика раз в секунду

    // Интервал между кадрами и якорь блока вывода берутся из PTS, а не из моментов прибытия:
    // у захвата своя дрожащая латентность (мс), и на 24/30 fps → 120 Гц она прямо входит в фазу —
    // это и есть judder. λ-фильтр (EMA скольжения pts→прибытие) держит якорь стабильным.
    int pts_phase    = 1;     // 1 = включить (нет валидных PTS у источника — тихий откат на якорь по моментам прибытия)
    // Аппаратный motion estimation Adreno (GL_QCOM_motion_estimation): вектора движения для WFG
    // берутся у аппаратного блока, DIS/Farneback остаётся фолбэком.
    // Требует EGL-контекст в процессе и гралок с расширением; экспериментально — по умолчанию выкл.
    int qcom_me      = 0;     // 1 = включить (нет расширения/ошибки GL — тихий откат на DIS)
    // временная медиана 17 + аппаратный сид, gain-компенсация экспозиции (фейды не ломают
    // поиск), защита центра экрана (HUD/прицел). Работает внутри GL-конвейера ME, поле
    // остаётся на GPU до блочной редукции в сетку блоков — контракт с WFG не меняется.
    // 0 — сырое аппаратное поле; 1 — лёгкое (4-угловая SAD, 5x5 вокруг сида);
    // 2 — полное (9-отводная SAD, 34 кандидата гексагональными кольцами 0.65..3.0 px).
    // Работает на ПОЛОВИННОМ разрешении luma (w/2 x h/2): в 4 раза
    // дешевле диспатч и память, точность для сетки блоков ME сохраняется. Нет ES 3.1 —
    // тихо работает как 0 (запись в лог).
    int me_refine    = 1;
    // Знак Y векторов аппаратного ME. Спека GL_QCOM_motion_estimation направление Y не
    // определяет; при старте игры модуль прогоняет самотест на синтетике (logcat: "dy self-test")
    // и приводит поле к координатам содержимого (y вниз), как ждёт WFG. 0 — самотест
    // (по умолчанию); 1 — драйвер отдаёт y вниз, без коррекции; 2 — драйвер отдаёт y вверх,
    // инверсия. Ручной ключ полезен, если самотест неубедителен, а интерполяция "плывёт" по
    // вертикали: меняется на ходу, результат виден сразу.
    int me_dy_sign   = 0;

    // ---- пейсинг с обратной связью -------------------------------------------------------------
    // В onComplete замеряется лэтч (getLatchTime, API 29) и
    // present (следующий vsync по фазовой сетке); err = present - ожидание таймлайна минус
    // медленный bias (постоянная задержка композита). Стабильное опоздание >= 0.6 слота —
    // выбору таймлайна разрешаются более ранние варианты (guard до +2.5 мс, ступени 250 мкс);
    // запас — надбавка тихо снимается. Работает при use_oncomplete и таймлайнах (API 33+).
    int pacing       = 1;     // 0 = контур выключен (только базовый выбор таймлайна)

    // ---- троттлинг по температуре батареи ------------------------------------------------------
    // Раз в 2 с читаем /sys/class/power_supply/battery/temp (0.1°C). Выше thermal_hi (два замера
    // подряд) вывод деградирует до thermal_hz: план генерации урезается до (thermal_hz/fps - 1),
    // голос частоты слоя, окна игры и якоря опускается — панель действительно уходит на 60 Гц,
    // а не остаётся на 120 с пустыми кадрами. Ниже thermal_lo (гистерезис) полный темп
    // возвращается. Нет датчика/файла — троттлинг тихо неактивен. По умолчанию выкл.
    int thermal      = 0;     // 1 = включить
    int thermal_hi   = 44;    // °C батареи, выше — деградация (35..60)
    int thermal_lo   = 40;    // °C батареи, ниже — восстановление (гистерезис, меньше hi)
    int thermal_hz   = 60;    // до скольки Гц деградировать вывод (30..144)

    void parse(const char* blob);
    void applyLive(const Config& n);   // переносит значения, которые безопасно менять на ходу
    void sanitize();          // приводит значения к допустимым диапазонам (WebUI и ручные правки могут дать любое)
};

extern Config g_cfg;
