#pragma once
// Аппаратный motion estimation Adreno — GL_QCOM_motion_estimation. Работает на общем
// GL-контексте модуля (gl_island, 1x1 pbuffer, не пересекается с контекстами игры),
// кадры берутся напрямую из буферов игры через EGLImage, luma-снимок защищён acquire-fence.
// Вектора читаются в host-буфер и передаются в WFG (vkr_dis_supply_flow); DIS остаётся
// фолбэком на каждый кадр (нет расширения/ошибка GL — тихий откат).
//
// GPU-уточнение аппаратного поля перед отдачей в WFG, встроено в наш GL-конвейер ME.
// me_refine: 0 — сырое поле, 1 — лёгкий режим (4-угловая SAD, 5x5 вокруг сида),
// 2 — полный (9-отводная SAD, 34 кандидата гексагональными кольцами). Оба режима:
// медиана 17 временного поля как второй сид, gain-компенсация экспозиции, защита центра
// экрана (HUD). Поле остаётся на GPU (rgba16f, ping-pong) до блочной редукции в сетку ME —
// readback и контракт с WFG не меняются. Работает на ПОЛОВИННОМ разрешении luma (w/2 x h/2):
// в 4 раза дешевле диспатч и память mvFull, точность для сетки блоков ME сохраняется;
// полное luma семплится LINEAR'ом (box 2x2), сид делится на 2, редукция возвращает пиксели luma.
// Требует ES 3.1; уточнение недоступно — тихо работаем с сырым полем.
// При инициализации прогоняется самотест знака Y (спека GL_QCOM_motion_estimation
// направление Y не определяет): синтетика с известным вертикальным сдвигом, медиана dy по блокам
// даёт направление оси драйвера, поле приводится к координатам содержимого (y вниз) — флип на CPU
// для сырого поля и uniform uDySign для сида в refine. Результат в логе ("dy self-test");
// ручной override — ключ me_dy_sign (0 самотест / 1 без флипа / 2 инверсия, live).
#include <android/hardware_buffer.h>
#include <stdint.h>

namespace qcomMe {

// Ленивая инициализация (один раз). false — модуль недоступен на этом устройстве
// (причина пишется в лог единожды): нет EGL, нет расширения, драйвер не даёт readback RGBA16F.
bool ensure();
bool available();

// Оборвать цепочку luma-снимков (кадр не прошёл через ME: WFG выключен/пересобран/пропуск).
// Следующий кадр станет первым в цепочке, пара (k-1, k+1) не получится.
void reset();

// Обработать очередной кадр (только на потоке конвейера). ahb — буфер игры (без нашей ссылки,
// ссылку модуль держит сам, пока живёт EGLImage), fence_fd — acquire-fence игры (dup'ается
// внутри, владение НЕ забирается; -1 = буфер готов), cl..cb — контент-рект в пикселях буфера.
// Возвращает true и заполняет vec/gw/gh: вектора (x,y) float, по одному на блок ME,
// прямые (ref -> target), в координатах содержимого (y вниз), в пикселях полного буфера.
// false — этого кадра нет (первый кадр цепочки, сброс, ошибка GL): конвейер уходит на DIS.
// vec живёт до следующего вызова frame().
bool frame(AHardwareBuffer* ahb, int fence_fd, int cl, int ct, int cr, int cb, int bw, int bh,
            const float** vec, uint32_t* gw, uint32_t* gh);

}
